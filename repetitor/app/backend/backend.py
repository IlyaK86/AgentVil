def detect_subject(message: str, history: list = None) -> str | None:
    """Lightweight keyword-based subject detection. Returns subject name or None.
    Examines current message + last 3 user messages for context.
    """
    text = (message or '').lower()
    if history:
        # Pull last 3 user messages for context
        for m in history[-6:]:
            if isinstance(m, dict) and m.get('role') == 'user':
                text += ' ' + m.get('content', '').lower()
    # Strip punctuation except letters and spaces
    import re as _re
    text = _re.sub(r'[^а-яёa-z0-9 \-]', ' ', text)

    scores = {}
    for subject, keywords in SUBJECT_KEYWORDS.items():
        score = 0
        for kw in keywords:
            # word boundary match
            if ' ' in kw:
                if kw in text:
                    score += 2  # phrase match counts more
            else:
                # use word boundary for short keywords
                if _re.search(r'\b' + _re.escape(kw) + r'\b', text):
                    score += 1
        scores[subject] = score
    if not scores:
        return None
    best = max(scores.items(), key=lambda x: x[1])
    if best[1] >= 2:  # threshold: at least 2 keyword hits
        return best[0]
    return None


