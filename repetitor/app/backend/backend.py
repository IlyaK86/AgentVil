def _strip_think(s: str) -> str:
    import re
    if not s:
        return ''
    # If there's a <think> block, strip it. Use non-greedy DOTALL.
    # But if the model forgets to close </think>, don't drop everything.
    if '<think>' in s:
        # Try to strip the think block properly (closed form)
        m = re.search(r'<think>(.*?)</think>(.*)', s, re.DOTALL)
        if m:
            rest = m.group(2).strip()
            if rest:
                return rest
            return ''  # closed think but empty after — model said nothing
        # No closing tag — model got stuck in thinking (response was truncated)
        if '</think>' not in s:
            # Find content AFTER the LAST <think> marker.
            # If model wrote a real answer INSIDE or after the unclosed think block,
            # there might be useful text there.
            parts = s.split('<think>')
            tail = parts[-1]
            tail = tail.replace('</think>', '').strip()
            if tail and len(tail) > 30:
                return tail
            # Nothing usable — model truly hung
            return ''
    return s.strip()

def _call_llm(system: str, user: str, temperature: float = 0.6, max_tokens: int = 1200, json_mode: bool = False) -> str:
    kwargs = dict(
        model='MiniMax-M3',
        messages=[
            {'role': 'system', 'content': system},
            {'role': 'user', 'content': user},
        ],
        temperature=temperature,
        max_tokens=max_tokens,
    )
    if json_mode:
        kwargs['response_format'] = {'type': 'json_object'}
    r = client.chat.completions.create(**kwargs)
    return _strip_think(r.choices[0].message.content)


def _llm_json(system: str, user: str, temperature: float = 0.4, max_tokens: int = 3000, retries: int = 1) -> dict:
    """Call the LLM expecting a JSON object. Tolerates ```json fences and extra prose;
    retries once if the reply is empty (reasoning can eat the token budget)."""
    last_err = None
    for _ in range(retries + 1):
        raw = _call_llm(system, user, temperature=temperature, max_tokens=max_tokens, json_mode=True)
        text = (raw or '').strip()
        if text.startswith('```'):
            text = text.strip('`')
            if text[:4].lower() == 'json':
                text = text[4:]
        start, end = text.find('{'), text.rfind('}')
        if start != -1 and end > start:
            try:
                return json.loads(text[start:end + 1])
            except Exception as e:
                last_err = e
        else:
            last_err = ValueError('empty or non-JSON LLM reply')
    raise last_err


