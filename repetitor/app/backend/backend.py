@app.get('/api/admin/student_analytics')
def admin_student_analytics(request: Request, user_id: int):
    """Comprehensive analytics for one student: profile, progress, insights, hard topics."""
    _require_admin(request)
    u = db.get_user(user_id)
    if not u:
        raise HTTPException(404, 'user_not_found')

    progress = db.list_progress(user_id, limit=100)
    # Group progress by subject
    by_subject = {}
    for p in progress:
        s = p['subject']
        if s not in by_subject:
            by_subject[s] = {
                'subject': s,
                'total_messages': 0, 'success': 0, 'struggle': 0,
                'topics': [],
                'last_seen_at': p['last_seen_at'],
            }
        agg = by_subject[s]
        agg['total_messages'] += p['message_count']
        agg['success'] += p['success_count']
        agg['struggle'] += p['struggle_count']
        agg['last_seen_at'] = max(agg['last_seen_at'], p['last_seen_at'])
        if p['topic']:
            agg['topics'].append({
                'topic': p['topic'],
                'count': p['message_count'],
                'success': p['success_count'],
                'struggle': p['struggle_count'],
                'last_seen_at': p['last_seen_at'],
                'confidence_avg': p.get('confidence_avg'),
            })
    # Sort topics within subject by last_seen_at desc
    for s in by_subject.values():
        s['topics'].sort(key=lambda x: x['last_seen_at'], reverse=True)

    # Latest insights per category
    insights = {}
    for cat in ('interests', 'strengths', 'weaknesses', 'style', 'overall'):
        ins = db.get_latest_insight(user_id, cat)
        if ins:
            insights[cat] = ins

    hard_topics = db.list_top_difficult_topics(user_id, limit=10)

    # Compute quick totals
    total_msgs = sum(s['total_messages'] for s in by_subject.values())
    total_success = sum(s['success'] for s in by_subject.values())
    total_struggle = sum(s['struggle'] for s in by_subject.values())

    return {
        'user': {
            'id': u['id'],
            'username': u.get('username'),
            'email': u['email'],
            'display_name': u.get('display_name'),
            'gender': u.get('gender'),
            'child_grade': u.get('child_grade', 4),
            'learning_style': u.get('learning_style'),
            'learning_style_note': u.get('learning_style_note'),
            'profile_completed_at': u.get('profile_completed_at'),
            'created_at': u.get('created_at'),
            'last_login_at': u.get('last_login_at'),
        },
        'summary': {
            'total_messages': total_msgs,
            'total_success': total_success,
            'total_struggle': total_struggle,
            'subjects_count': len(by_subject),
            'satisfaction_pct': round(100 * total_success / max(1, total_success + total_struggle)) if (total_success + total_struggle) else None,
        },
        'by_subject': list(by_subject.values()),
        'insights': insights,
        'hard_topics': hard_topics,
    }


