def _extract_topic_from_message(message: str, subject: str) -> str:
    """Quick LLM call: extract a 2-4 word topic name from a message.
    Returns empty string if not confident.
    """
    if not message or len(message.strip()) < 5:
        return ''
    try:
        sys = (
            'Ты — ассистент, который извлекает из вопроса ученика тему (2-4 слова). '
            'Ответь СТРОГО одним JSON: {"topic": "..."}. '
            'Примеры:\n'
            'Q: "что такое причастный оборот" → {"topic": "причастный оборот"}\n'
            'Q: "как решать квадратные уравнения" → {"topic": "квадратные уравнения"}\n'
            'Q: "привет, как дела" → {"topic": ""}\n'
            'Если вопрос не относится к учёбе — верни пустую строку.'
        )
        prompt = f'Предмет: {subject or "любой"}\nВопрос ученика: {message[:500]}'
        raw = _call_llm(sys, prompt, temperature=0.2, max_tokens=60, json_mode=True)
        import re as _re
        m = _re.search(r'"topic"\s*:\s*"([^"]*)"', raw)
        if m:
            return m.group(1).strip()[:60]
    except Exception as e:
        print(f'[extract_topic] error: {e}', flush=True)
    return ''


def _generate_insights_for_user(user_id: int) -> None:
    """Background task: pull recent messages, run LLM analytics, save insights.
    Categories: interests, strengths, weaknesses, style, overall.
    """
    try:
        with db.get_conn() as c:
            user = c.execute('SELECT * FROM users WHERE id = ?', (user_id,)).fetchone()
            if not user:
                return
            user = dict(user)
            # Pull last 30 user-assistant exchanges
            logs = c.execute('''
                SELECT role, content, subject, rating FROM chat_logs
                WHERE user_id = ? AND role IN ('user', 'assistant')
                ORDER BY id DESC LIMIT 60
            ''', (user_id,)).fetchall()
        if len(logs) < 6:
            return  # too few to analyze

        logs = list(reversed([dict(r) for r in logs]))
        # Build a condensed transcript (user msgs + truncated assistant)
        lines = []
        for l in logs:
            role = l['role']
            content = (l['content'] or '')[:400]
            subj = l.get('subject') or ''
            prefix = '[УЧЕНИК]' if role == 'user' else '[РЕПЕТИТОР]'
            if subj:
                prefix += f' ({subj})'
            lines.append(f'{prefix}: {content}')
        transcript = '\n'.join(lines)
        n_user_msgs = sum(1 for l in logs if l['role'] == 'user')

        user_meta = (
            f'Имя: {user.get("display_name") or "—"}\n'
            f'Пол: {user.get("gender") or "—"}\n'
            f'Класс: {user.get("child_grade", 4)}\n'
            f'Стиль обучения: {user.get("learning_style") or "—"}\n'
            f'Заметки: {user.get("learning_style_note") or "—"}'
        )

        sys_prompt = (
            'Ты — аналитик обучения школьника. Тебе дан диалог с репетитором.\n'
            'Твоя задача — извлечь 5 категорий инсайтов и вернуть СТРОГО валидный JSON.\n\n'
            'Структура JSON:\n'
            '{\n'
            '  "interests": "краткое описание (2-3 предложения) чем интересуется ученик, какие темы его привлекают",\n'
            '  "interests_details": [{"item": "тема", "evidence": "цитата из диалога"}, ...],\n'
            '  "strengths": "краткое описание (2-3 предложения) в чём ученик силён, что даётся легко",\n'
            '  "strengths_details": [{"item": "навык", "evidence": "цитата"}, ...],\n'
            '  "weaknesses": "краткое описание (2-3 предложения) где нужна помощь, какие темы тяжелы",\n'
            '  "weaknesses_details": [{"item": "тема", "evidence": "цитата"}, ...],\n'
            '  "style": "краткое описание (2-3 предложения) как ученику лучше учиться — '
            'любит примеры из игр/жизни, любит разбирать по шагам, любит тесты, и т.п.",\n'
            '  "style_details": [{"item": "предпочтение", "evidence": "цитата"}, ...],\n'
            '  "overall": "общее резюме ученика в 1-2 предложения — кто он как ученик"\n'
            '}\n\n'
            'ВАЖНО:\n'
            '- Пиши на русском, простым языком для родителя.\n'
            '- В evidence цитируй 5-15 слов из диалога.\n'
            '- Если данных мало — пиши «недостаточно данных».\n'
            '- НЕ придумывай, только по диалогу.'
        )
        user_prompt = f'Профиль ученика:\n{user_meta}\n\nПоследние {n_user_msgs} вопросов ученика:\n\n{transcript}'

        try:
            data = _llm_json(sys_prompt, user_prompt, temperature=0.4, max_tokens=3000)
        except Exception as e:
            print(f'[insights] LLM error: {e}', flush=True)
            return

        # Save each category as a separate insight row
        model_ver = 'MiniMax-M3'
        messages_analyzed = n_user_msgs
        for cat in ('interests', 'strengths', 'weaknesses', 'style', 'overall'):
            summary = (data.get(cat) or '').strip()
            if not summary or summary.lower() in ('недостаточно данных', 'нет данных'):
                continue
            details_key = cat + '_details'
            details = data.get(details_key) if cat != 'overall' else None
            db.save_insight(
                user_id=user_id,
                category=cat,
                summary=summary,
                details=details,
                messages_analyzed=messages_analyzed,
                model_version=model_ver,
            )
        print(f'[insights] generated for user {user_id} ({n_user_msgs} msgs)', flush=True)
    except Exception as e:
        print(f'[insights] outer error: {e}', flush=True)


def _maybe_run_insights_async(user_id: int) -> None:
    """Trigger background analytics if enough new messages accumulated."""
    try:
        n = db.count_messages_since_last_insight(user_id)
        if n >= INSIGHT_TRIGGER_MESSAGES:
            import threading
            t = threading.Thread(target=_generate_insights_for_user, args=(user_id,), daemon=True)
            t.start()
    except Exception as e:
        print(f'[insights] trigger error: {e}', flush=True)


