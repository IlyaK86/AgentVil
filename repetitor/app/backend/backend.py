def is_query_blocked(message: str) -> bool:
    """Проверяет вопрос ребёнка на стоп-слова. True = блокируем."""
    msg_lower = (message or '').lower()
    for w in BLOCKED_QUERY_WORDS:
        if w in msg_lower:
            return True
    return False


def web_search_for_kid(query: str, max_results: int = 4, timeout_sec: int = 12) -> str:
    """
    Детский веб-поиск: ищет через DDG, фильтрует по доменам,
    возвращает до 3 коротких выжимок со ссылками.
    """
    import re as _re
    import subprocess as _sp

    try:
        # Запускаем web_parser_v2.py как subprocess — изолировано от LLM
        result = _sp.run(
            ['python3', '/opt/vilavi-dashboard/web_parser_v2.py', 'search', '--query', query],
            capture_output=True, text=True, timeout=timeout_sec,
        )
        if result.returncode != 0 or not result.stdout.strip():
            return ''
        results = json.loads(result.stdout)
        if not isinstance(results, list):
            return ''
    except Exception as e:
        print(f'[web_search] DDG error: {e}', flush=True)
        return ''

    # Декодируем DDG URL и фильтруем домены
    accepted = []
    for r in results[:max_results * 2]:
        title = r.get('title', '').strip()
        url_raw = r.get('url', '')
        # DDG: //duckduckgo.com/l/?uddg=ENCODED → достаём реальный URL
        m = _re.search(r'uddg=([^&]+)', url_raw)
        if m:
            from urllib.parse import unquote
            url = unquote(m.group(1))
        else:
            url = url_raw

        url_lower = url.lower()

        # Чёрный список — никогда не берём
        if any(b in url_lower for b in BLOCKED_DOMAINS):
            continue

        # Whitelist предпочтительна, но если не нашлось — берём остальное
        is_safe = any(d in url_lower for d in SAFE_DOMAINS)
        accepted.append({
            'title': title,
            'url': url,
            'safe': is_safe,
        })
        if len(accepted) >= max_results * 2:
            break

    # Сначала safe, потом остальное
    safe_first = sorted(accepted, key=lambda x: 0 if x['safe'] else 1)
    safe_first = safe_first[:max_results]

    if not safe_first:
        return ''

    # Достаём краткое содержимое первой безопасной ссылки
    parts = []
    for i, item in enumerate(safe_first, 1):
        snippet = ''
        if item['safe']:
            try:
                # Пробуем достать короткое содержимое (первый абзац)
                extract = _sp.run(
                    ['python3', '/opt/vilavi-dashboard/web_parser_v2.py', 'extract', '--url', item['url']],
                    capture_output=True, text=True, timeout=8,
                )
                if extract.returncode == 0 and extract.stdout.strip():
                    data = json.loads(extract.stdout)
                    snippet = (data.get('text') or data.get('description') or '')[:600]
            except Exception:
                pass
        parts.append(f'[{i}] {item["title"]}\nURL: {item["url"]}\n{snippet}')

    return '\n\n---\n\n'.join(parts)

