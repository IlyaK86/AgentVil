@app.post('/api/slides')
def slides(req: TransformRequest):
    """Generate presentation slides as JSON. Try multiple formats."""
    sys_flat = (
        "Ты — дизайнер презентаций для школьницы. Преврати объяснение в 8 слайдов. "
        "КРИТИЧНО: выведи ТОЛЬКО валидный JSON-объект, начинающийся с { и заканчивающийся }. "
        "НЕ оборачивай JSON в строку. НЕ используй markdown. Без пояснений.\n"
        "Формат — плоские ключи:\n"
        '{"title": "...", '
        '"slide_1": {"emoji": "📘", "heading": "...", "body": ["...", "...", "..."], "highlight": "...", "narration": "..."}, '
        '"slide_2": {...}, ... "slide_8": {...}}\n'
        "- slide_1: 'Что мы изучим' — 3-4 пункта.\n"
        "- Средние: по одной подтеме, body = 3 пункта.\n"
        "- Последний: 'Главное за 30 секунд' — 3-4 тезиса.\n"
        "- highlight — главная мысль (1 предложение).\n"
        "- narration — текст для TTS-озвучки (2-3 предложения).\n"
        "- Emoji — 1 штука, релевантная теме."
    )
    sys_list = (
        "Ты — дизайнер презентаций для школьницы. Преврати объяснение в 8 слайдов. "
        "КРИТИЧНО: выведи ТОЛЬКО валидный JSON-объект. "
        "НЕ оборачивай в строку. Без markdown.\n"
        '{"title": "...", "slides": ['
        '{"emoji": "📘", "heading": "...", "body": ["...", "...", "..."], "highlight": "...", "narration": "..."}, '
        '...]}\n'
        "- slide_1: 'Что мы изучим'.\n"
        "- Средние: по подтеме.\n"
        "- Последний: 'Главное за 30 секунд'.\n"
        "- highlight — главная мысль. narration — текст для TTS. Emoji — 1 шт."
    )
    user = f"Предмет: {req.subject or 'не указан'}\n\nОбъяснение:\n{req.text[:4500]}"

    # Try flat format first (more reliable for this model)
    raw = _call_llm(sys_flat, user, temperature=0.4, max_tokens=2500, json_mode=True)

    def parse(raw_text):
        if not raw_text:
            return None
        try:
            data = json.loads(raw_text)
        except Exception:
            return None
        if not isinstance(data, dict):
            return None
        # Format A: flat slide_1, slide_2 ...
        flat = []
        for k, v in data.items():
            if k.startswith('slide_') and isinstance(v, dict):
                flat.append(v)
        if flat:
            return {'title': data.get('title', 'Презентация'), 'slides': flat}
        # Format B: nested slides array
        if 'slides' in data and isinstance(data['slides'], list) and data['slides']:
            return {'title': data.get('title', 'Презентация'), 'slides': data['slides']}
        # Format C: nested slides array but as single object
        if 'slides' in data and isinstance(data['slides'], dict):
            return {'title': data.get('title', 'Презентация'), 'slides': [data['slides']]}
        return None

    parsed = parse(raw)
    if parsed and len(parsed['slides']) >= 3:
        return {'slides': parsed}

    # Fallback: try list format
    raw2 = _call_llm(sys_list, user, temperature=0.4, max_tokens=2500, json_mode=True)
    parsed2 = parse(raw2)
    if parsed2 and len(parsed2['slides']) >= 3:
        return {'slides': parsed2}

    # Last resort: extract any JSON from raw text
    if raw:
        # Try to extract title and best-effort parse
        try:
            j = json.loads(raw)
            if isinstance(j, dict) and j.get('title'):
                # If it has any slide-like structure, use as-is
                if 'slides' in j:
                    return {'slides': {'title': j['title'], 'slides': j['slides'] if isinstance(j['slides'], list) else [j['slides']]}}
        except Exception:
            pass

    # Absolute fallback: one slide with raw text
    return {'slides': {'title': 'Презентация', 'slides': [
        {'emoji': '📘', 'heading': 'Конспект', 'body': [(raw or '')[:500]], 'highlight': '', 'narration': ''}
    ]}}


