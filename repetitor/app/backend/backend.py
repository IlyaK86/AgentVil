def get_current_user(request: Request) -> dict | None:
    """Extract user from session token in cookie or Authorization header."""
    token = None
    auth = request.headers.get('Authorization', '')
    if auth.startswith('Bearer '):
        token = auth[7:]
    if not token:
        token = request.cookies.get('rp_session')
    if not token:
        return None
    return db.find_session(token)


def require_user(request: Request) -> dict:
    """Dependency: get user or 401."""
    u = get_current_user(request)
    if not u:
        raise HTTPException(401, 'not_authenticated')
    return u


def require_access(request: Request) -> dict:
    """Dependency: get user with active access or 403."""
    u = require_user(request)
    ok, reason = db.user_has_access(u)
    if not ok:
        raise HTTPException(403, f'no_access:{reason}')
    return u


def _send_magic_email(email: str, magic_url: str) -> bool:
    """Send magic link via SMTP. Returns True if sent (or queued to log)."""
    if not SMTP_HOST or not SMTP_USER:
        # Dev mode: log to file
        with open('/tmp/repetitor_emails.log', 'a') as f:
            f.write(f'\n--- {time.strftime("%Y-%m-%d %H:%M:%S")} ---\nTo: {email}\nMagic URL: {magic_url}\n')
        return True
    try:
        import smtplib
        from email.mime.text import MIMEText
        msg = MIMEText(f'Здравствуйте!\n\nВойдите в ИИ-Репититор по ссылке (действует 24 часа):\n\n{magic_url}\n\nЕсли вы не запрашивали вход — просто проигнорируйте это письмо.\n')
        msg['Subject'] = 'Вход в ИИ-Репититор'
        msg['From'] = SMTP_FROM
        msg['To'] = email
        with smtplib.SMTP(SMTP_HOST, SMTP_PORT, timeout=15) as s:
            s.starttls()
            s.login(SMTP_USER, SMTP_PASS)
            s.send_message(msg)
        return True
    except Exception as e:
        print(f'[smtp] error: {e}', flush=True)
        # Fallback to log
        with open('/tmp/repetitor_emails.log', 'a') as f:
            f.write(f'\n--- {time.strftime("%Y-%m-%d %H:%M:%S")} (SMTP FAILED) ---\nTo: {email}\nMagic URL: {magic_url}\nError: {e}\n')
        return True


