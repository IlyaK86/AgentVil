@app.post('/api/stt')
async def stt(audio: UploadFile = File(...)):
    """Speech-to-text via faster-whisper."""
    from faster_whisper import WhisperModel
    data = await audio.read()
    ct = audio.content_type or 'audio/webm'
    suffix = '.webm' if 'webm' in ct else ('.ogg' if 'ogg' in ct else '.wav')
    with tempfile.NamedTemporaryFile(suffix=suffix, delete=False) as f:
        f.write(data)
        audio_path = f.name

    try:
        wav_path = audio_path
        if suffix in ('.webm', '.ogg'):
            wav_path = audio_path + '.wav'
            r = subprocess.run(
                ['ffmpeg', '-y', '-i', audio_path, '-ar', '16000', '-ac', '1', wav_path],
                capture_output=True, timeout=30
            )
            if r.returncode != 0:
                raise HTTPException(500, f'ffmpeg error: {r.stderr.decode()[:200]}')

        model = WhisperModel('base', device='cpu', compute_type='int8')
        segments, info = model.transcribe(wav_path, language='ru')
        text = ''.join(seg.text for seg in segments).strip()
        return {'text': text, 'duration': info.duration, 'language': info.language}
    finally:
        for p in [audio_path, wav_path]:
            try: os.unlink(p)
            except: pass


